#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md: every crate linked into the macOS library,
with its licence expression and the licence texts it ships.

Only normal (not dev or build) dependencies reachable from the crate, for the
two Apple targets the xcframework is built for. Texts come from each crate's
own LICENSE*/COPYING*/NOTICE* files in the Cargo registry (run
`cargo fetch --locked` first); identical texts are printed once, with the
crates that share them. A crate that ships no licence file is listed as such
and fails the check (`--check`), so a missing notice cannot go unnoticed.

Usage: scripts/third_party_licenses.py [--check]
Standard library only.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CRATE = ROOT / "rust"
OUT = ROOT / "THIRD_PARTY_LICENSES.md"
TARGETS = ["aarch64-apple-darwin", "x86_64-apple-darwin"]
PREFIXES = ("license", "licence", "copying", "notice", "unlicense")
# Crates that publish no licence file: texts taken from upstream (licenses/README.md).
SUPPLIED = {"bitfields": "bitfields", "bitfields-impl": "bitfields", "crc24": "crc24"}
# Crates with no licence text anywhere upstream (licenses/README.md says why).
ACKNOWLEDGED = {"cx448"}


def metadata(target: str) -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--filter-platform", target],
        cwd=CRATE, check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def linked_packages() -> dict:
    found = {}
    for target in TARGETS:
        data = metadata(target)
        nodes = {n["id"]: n for n in data["resolve"]["nodes"]}
        packages = {p["id"]: p for p in data["packages"]}
        root = next(p["id"] for p in data["packages"] if p["name"] == "dreamail-rpgp")
        stack, seen = [root], set()
        while stack:
            node = stack.pop()
            if node in seen:
                continue
            seen.add(node)
            for dep in nodes[node]["deps"]:
                if any(kind["kind"] is None for kind in dep["dep_kinds"]):
                    stack.append(dep["pkg"])
        for package_id in seen - {root}:
            found[package_id] = packages[package_id]
    return found


def licence_files(package: dict) -> list[Path]:
    directory = Path(package["manifest_path"]).parent
    files = sorted(p for p in directory.iterdir()
                   if p.is_file() and p.name.lower().startswith(PREFIXES))
    if not files and package["name"] in SUPPLIED:
        files = sorted((ROOT / "licenses" / SUPPLIED[package["name"]]).iterdir())
    return files


def main(argv: list[str]) -> int:
    packages = sorted(linked_packages().values(), key=lambda p: (p["name"], p["version"]))
    texts: dict[str, dict] = {}
    missing = []
    rows = []
    for package in packages:
        label = f"{package['name']} {package['version']}"
        files = licence_files(package)
        rows.append(f"| {package['name']} | {package['version']} | {package.get('license') or '?'} |")
        if not files:
            missing.append(label)
        for path in files:
            body = path.read_text(encoding="utf-8", errors="replace").strip()
            key = hashlib.sha256(body.encode()).hexdigest()
            texts.setdefault(key, {"body": body, "users": []})["users"].append(f"{label} ({path.name})")

    lines = [
        "# Third-party licences",
        "",
        "Generated by `scripts/third_party_licenses.py` from `rust/Cargo.lock`: every crate",
        "linked into `DreaMailRPGP.xcframework` (macOS arm64 and x86_64), then the licence",
        "texts the crates ship, each printed once. Do not edit by hand.",
        "",
        f"{len(packages)} crates.",
        "",
        "| Crate | Version | Licence |",
        "|---|---|---|",
        *rows,
        "",
    ]
    if missing:
        lines += ["## Crates without a licence text", "",
                  "No text in the published crate or its repository (licenses/README.md).", "",
                  *[f"- {label}" for label in missing], ""]
    for entry in sorted(texts.values(), key=lambda e: e["users"][0]):
        lines += ["---", "", "Used by: " + ", ".join(entry["users"]), "", "```text", entry["body"], "```", ""]
    content = "\n".join(lines)

    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        problems = []
        if current != content:
            problems.append(f"{OUT.name} is out of date: run scripts/third_party_licenses.py")
        problems += [f"no licence file shipped by {label}" for label in missing
                     if label.split(" ")[0] not in ACKNOWLEDGED]
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT.name}: {len(packages)} crates, {len(texts)} distinct texts, "
          f"{len(missing)} without a licence file")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
